class TorchAdapter:
    """Unified adapter for PyTorch models to provide consistent predict interface.
    
    Used by src.Centralized to evaluate models on test sets.
    """
    def __init__(self, model, label_encoder, is_binary: bool, batch: int = 32, device=None):
        self.model = model
        self.le = label_encoder
        self.is_binary = is_binary
        self.batch = batch
        self.device = device or (next(model.parameters()).device if model else None)
        
    def predict(self, paths):
        """Predict labels for given record paths."""
        from src.data_preprocessing import make_predict_loader
        loader = make_predict_loader(paths, device=self.device, batch_size=self.batch)
        
        self.model.eval()
        preds = []
        with torch.no_grad():
            for xb in loader:
                if isinstance(xb, (list, tuple)):
                    xb = xb[0]
                xb = xb.to(self.device)
                logits = self.model(xb)
                if self.is_binary:
                    pred = (torch.sigmoid(logits.view(-1)) >= 0.5).long().cpu().numpy()
                else:
                    pred = logits.argmax(1).cpu().numpy()
                preds.extend(pred)
        
        return self.le.inverse_transform(np.array(preds))


def evaluate_models(adapters: Dict, test_paths, y_true, label_encoder, is_binary: bool, device):
    """Evaluate multiple models and return comparison DataFrame."""
    from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score
    
    rows = []
    for name, adapter in adapters.items():
        y_pred = adapter.predict(test_paths)
        
        rows.append({
            "model": name,
            "accuracy": accuracy_score(y_true, y_pred),
            "precision_macro": precision_score(y_true, y_pred, average="macro", zero_division=0),
            "recall_macro": recall_score(y_true, y_pred, average="macro", zero_division=0),
            "f1_macro": f1_score(y_true, y_pred, average="macro", zero_division=0),
            "f1_weighted": f1_score(y_true, y_pred, average="weighted", zero_division=0),
        })
    
    df = pd.DataFrame(rows).sort_values("accuracy", ascending=False)
    return df


def plot_confusion(y_true, y_pred, title="Confusion Matrix", save_path=None, collapse_to_3=False):
    """Generate confusion matrix heatmap with counts and percentages."""
    from sklearn.metrics import confusion_matrix
    
    labels = sorted(set(y_true) | set(y_pred))
    cm = confusion_matrix(y_true, y_pred, labels=labels)
    
    # Save counts
    if save_path:
        counts_csv = Path(save_path).parent / f"{Path(save_path).stem}_counts.csv"
        pd.DataFrame(cm, index=labels, columns=labels).to_csv(counts_csv)
        _savetab(pd.DataFrame(cm, index=labels, columns=labels), counts_csv.parent, counts_csv.name)
    
    # Normalize
    with np.errstate(invalid="ignore", divide="ignore"):
        cmn = cm / cm.sum(axis=1, keepdims=True)
        cmn = np.nan_to_num(cmn)
    
    # Save percentages
    if save_path:
        pct_csv = Path(save_path).parent / f"{Path(save_path).stem}_percent.csv"
        _savetab(pd.DataFrame(cmn * 100, index=labels, columns=labels).round(2), pct_csv.parent, pct_csv.name)
    
    # Plot
    fig, ax = plt.subplots(figsize=(8, 6))
    im = ax.imshow(cmn, aspect="auto", vmin=0, vmax=1, cmap="Blues")
    ax.set_title(title)
    ax.set_xlabel("Predicted")
    ax.set_ylabel("True")
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=45, ha="right")
    ax.set_yticks(range(len(labels)))
    ax.set_yticklabels(labels)
    
    # Add text annotations
    for i in range(len(labels)):
        for j in range(len(labels)):
            val = cmn[i, j] * 100
            ax.text(j, i, f"{val:.1f}%", ha="center", va="center",
                   color="white" if val > 50 else "black", fontsize=9)
    
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Row-normalized")
    plt.tight_layout()
    
    if save_path:
        ensure_dir(Path(save_path).parent)
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
        log(f"Saved confusion matrix: {save_path}")
    plt.close(fig)


def plot_learning_curves(histories: Dict[str, Dict], out_dir: str):
    """Plot training/validation curves from model histories."""
    out_dir = Path(out_dir)
    ensure_dir(out_dir)
    
    for name, hist in histories.items():
        if not hist or "loss" not in hist:
            continue
            
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))
        
        epochs = range(1, len(hist["loss"]) + 1)
        
        # Loss
        ax1.plot(epochs, hist["loss"], label="Train")
        ax1.plot(epochs, hist["val_loss"], label="Validation")
        ax1.set_xlabel("Epoch")
        ax1.set_ylabel("Loss")
        ax1.set_title(f"{name} - Loss")
        ax1.legend()
        ax1.grid(alpha=0.3)
        
        # Accuracy
        ax2.plot(epochs, hist["accuracy"], label="Train")
        ax2.plot(epochs, hist["val_accuracy"], label="Validation")
        ax2.set_xlabel("Epoch")
        ax2.set_ylabel("Accuracy")
        ax2.set_title(f"{name} - Accuracy")
        ax2.legend()
        ax2.grid(alpha=0.3)
        
        plt.tight_layout()
        safe_name = name.replace(" ", "_").replace("(", "").replace(")", "")
        savefig(fig, out_dir, f"learning_curves_{safe_name}.png")


