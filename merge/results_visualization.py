# Smoothing (rolling mean)
SMOOTH = int(os.getenv("SMOOTH", "1"))  # 1 = off; 3/5 for presentation
def smooth(y):
    if SMOOTH <= 1:
        return y
    s = pd.Series(y, dtype=float)
    return s.rolling(SMOOTH, min_periods=1).mean().to_numpy()

def load_numeric_csv(path: Path):
    if not path.exists():
        print(f"Missing: {path}")
        return None
    df = pd.read_csv(path)
    for col in ["round","accuracy","loss","wall_time_sec","trainable_params","true","pred","count"]:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")
    return df


def visualize_fl_results(results_dir: Path = RESULTS_DIR, out_dir: Path = None):
    """Generate all FL visualization plots from CSV logs."""
    if out_dir is None:
        out_dir = results_dir / "viz"
    ensure_dir(out_dir)
    
    # Auto-discover runs per model (cnn/lstm)
    runs = {}
    pat = re.compile(r"^(?P<model>[^_]+)_(?P<kind>non_frozen|frozen)_run$")
    for p in results_dir.glob("*_*_run.csv"):
        m = pat.match(p.stem)
        if not m:
            continue
        model = m.group("model")
        kind = m.group("kind")
        runs.setdefault(model, {})[kind] = p
    
    for model, paths in runs.items():
        for kind, csv_path in paths.items():
            df = load_numeric_csv(csv_path)
            if df is None or df.empty:
                continue
            
            # Global accuracy vs round
            global_df = df[df["client_id"] == "GLOBAL"].copy()
            if not global_df.empty:
                fig, ax = plt.subplots(figsize=(10, 5))
                ax.plot(global_df["round"], smooth(global_df["accuracy"]), linewidth=2)
                ax.set_xlabel("Round")
                ax.set_ylabel("Accuracy")
                ax.set_title(f"Global Accuracy — {model.upper()} {kind}")
                ax.grid(alpha=0.3)
                plt.tight_layout()
                savefig(fig, out_dir, f"global_acc_{model}_{kind}.png")
            
            # Per-client trajectories
            client_df = df[df["client_id"] != "GLOBAL"].copy()
            if not client_df.empty:
                fig, ax = plt.subplots(figsize=(10, 5))
                for cid, grp in client_df.groupby("client_id"):
                    grp = grp.sort_values("round")
                    ax.plot(grp["round"], smooth(grp["accuracy"]), alpha=0.7, label=f"Client {cid}")
                ax.set_xlabel("Round")
                ax.set_ylabel("Accuracy")
                ax.set_title(f"Per-Client Accuracy — {model.upper()} {kind}")
                ax.legend()
                ax.grid(alpha=0.3)
                plt.tight_layout()
                savefig(fig, out_dir, f"client_acc_{model}_{kind}.png")
    
    log(f"FL visualization complete. Outputs in: {out_dir}")


